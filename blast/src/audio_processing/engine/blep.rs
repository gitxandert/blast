//! Band-limited steps for the oscillators: a port of Signalsmith Audio's
//! elliptic-blep (MIT), Copyright 2024 Signalsmith Audio Ltd. / Geraint Luff
//! (reference commit 77bf986; the licence is in `LICENSE-elliptic-blep`).
//!
//! The filter is an 11th-order continuous-time elliptic lowpass (0.1 dB
//! ripple, 97.5 dB stop band, 20 kHz at 44.1 kHz), written as a sum of eight
//! one-pole filters (2 real poles, 6 complex ones) whose states can be moved
//! forward and back by fractions of a sample. A discontinuity in a waveform
//! (a step, a change of slope) is `add`ed to the states as the filter's
//! response to it; `get` sums the states into the correction to add to the
//! naive waveform, and `step` moves them on one sample.
//!
//! Only the "BLEP" (residue) mode is ported: no direct mode, and not the
//! allpass that makes the phase linear (it costs latency).
//!
//! Real time: everything that depends on the sample rate (the poles raised
//! to fractional powers, the coefficients) lives in a `BlepTable`, built once
//! when the engine is made (never on the audio thread) and shared by
//! reference. The state of one oscillator instance is a fixed `BlepState`.

/// The poles: 2 real and 6 complex ones, treated alike.
pub const POLES: usize = 8;

/// The highest order of discontinuity (0 impulse, 1 step, 2 slope change, 3).
const MAX_ORDER: usize = 3;

/// Table resolution: fractions of a sample are `1 / PARTIAL_STEPS`.
const PARTIAL_STEPS: usize = 127;

/// A complex number (this module's own; no crate for it).
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct C {
    pub re: f64,
    pub im: f64,
}

impl C {
    const ZERO: C = C { re: 0.0, im: 0.0 };

    const fn new(re: f64, im: f64) -> C {
        C { re, im }
    }

    fn mul(self, o: C) -> C {
        C::new(
            self.re * o.re - self.im * o.im,
            self.re * o.im + self.im * o.re,
        )
    }

    fn scale(self, k: f64) -> C {
        C::new(self.re * k, self.im * k)
    }

    fn div(self, o: C) -> C {
        let d = o.re * o.re + o.im * o.im;
        C::new(
            (self.re * o.re + self.im * o.im) / d,
            (self.im * o.re - self.re * o.im) / d,
        )
    }

    fn exp(self) -> C {
        let m = self.re.exp();
        C::new(m * self.im.cos(), m * self.im.sin())
    }
}

// The pre-designed filter (generated by upstream's design.py). The real
// poles come first, then the complex ones: the order `EllipticBlep` indexes
// them in.
const POLE: [C; POLES] = [
    C::new(-19.99999999999999, 0.0),
    C::new(-6297.997056605768, 0.0),
    C::new(-10.000000000000018, 17.32050807568877),
    C::new(-5561.9825585455355, 7721.564144482811),
    C::new(-3936.722737570645, 13650.19780181135),
    C::new(-2348.139919172614, 17360.27161948123),
    C::new(-1177.5927594532213, 19350.80475283612),
    C::new(-351.8363400542262, 20192.23851486371),
];

// the residues of the pure elliptic filter's impulse response (the real pole
// at -20 Hz and the first complex pair carry none): step and ramp
// responses are these divided by the poles, so the stop band is the filter's
// own (about -100 dB). Upstream's `COEFF_BLEP` set is DC-safe (it dies away
// after a change of slope) but its stop band is only about -55 dB, so it is
// not used (HPR rev 2).
const COEFF_IMPULSE: [C; POLES] = [
    C::new(-0.0, 0.0),
    C::new(10260.028875848622, 0.0),
    C::new(-0.0, 0.0),
    C::new(-16437.986654210414, -7224.765894589258),
    C::new(7790.757942542475, 9526.642450546504),
    C::new(-840.5346697230617, -6786.810488746716),
    C::new(-1524.1587677330679, 2562.995919504876),
    C::new(754.6036883967192, -311.8275441795608),
];

/// One filter's eight complex numbers, real and imaginary parts apart (so
/// the loops over the poles run as vector operations).
#[derive(Clone, Copy, Debug)]
pub struct Lanes {
    re: [f64; POLES],
    im: [f64; POLES],
}

impl Lanes {
    const ZERO: Lanes = Lanes {
        re: [0.0; POLES],
        im: [0.0; POLES],
    };

    /// Whether every state is exactly zero (nothing is ringing).
    pub fn is_silent(&self) -> bool {
        self.re.iter().chain(&self.im).all(|x| *x == 0.0)
    }
}

/// One oscillator instance's filter state.
pub type BlepState = Lanes;

/// The state of a quiet filter.
pub const QUIET: BlepState = Lanes::ZERO;

/// What depends on the sample rate: the poles raised to fractional powers
/// (so the state can move by any fraction of a sample) and the coefficients
/// for each order. Built once, shared by every oscillator.
pub struct BlepTable {
    // `exp(pole * s / PARTIAL_STEPS)` for s in 0..=PARTIAL_STEPS
    partial: [Lanes; PARTIAL_STEPS + 1],
    // `coefficient * exp(pole * s / PARTIAL_STEPS)` for each order: what an
    // event adds to the states, before the interpolation between entries
    ready: [[Lanes; PARTIAL_STEPS + 1]; MAX_ORDER + 1],
    // the constant the response to a change of slope settles on, per unit of
    // slope per sample: minus the filter's DC group delay in samples
    ramp_offset: f64,
    // the time after a step at which the filter's output reaches half its
    // height, in samples
    half_time: f64,
}

impl BlepTable {
    /// The table for `sample_rate` (allocates: build it off the audio thread).
    pub fn new(sample_rate: f64) -> Box<BlepTable> {
        let hz_to_angular = std::f64::consts::TAU / sample_rate;
        let mut t = Box::new(BlepTable {
            partial: [Lanes::ZERO; PARTIAL_STEPS + 1],
            ready: [[Lanes::ZERO; PARTIAL_STEPS + 1]; MAX_ORDER + 1],
            ramp_offset: 0.0,
            half_time: 0.0,
        });
        let mut ramp = 0.0;
        for i in 0..POLES {
            let pole = POLE[i].scale(hz_to_angular);
            let mut partial = [C::ZERO; PARTIAL_STEPS + 1];
            for (s, p) in partial.iter_mut().enumerate() {
                *p = pole.scale(s as f64 / PARTIAL_STEPS as f64).exp();
                t.partial[s].re[i] = p.re;
                t.partial[s].im[i] = p.im;
            }
            // integrate the impulse response to get the higher orders
            let mut c = COEFF_IMPULSE[i].scale(hz_to_angular);
            for order in 0..=MAX_ORDER {
                if order > 0 {
                    c = c.div(pole);
                }
                if order == 2 {
                    ramp += c.re;
                }
                for (s, p) in partial.iter().enumerate() {
                    let r = c.mul(*p);
                    t.ready[order][s].re[i] = r.re;
                    t.ready[order][s].im[i] = r.im;
                }
            }
        }
        // a ramp's response ends on a constant, not on 0 (the filter delays it)
        t.ramp_offset = -ramp;
        t.half_time = t.find_half_time();
        t
    }

    // where the response to a unit step first crosses 0.5, found on a grid
    // of 1/16 sample and refined by a line (called when the table is built)
    fn find_half_time(&self) -> f64 {
        const GRID: usize = 16;
        let mut before = (0.0, 0.0);
        for k in 0..64 {
            for g in 0..GRID {
                let f = g as f64 / GRID as f64;
                let mut s = QUIET;
                self.add(&mut s, 1.0, 1, f);
                for _ in 0..k {
                    self.step(&mut s);
                }
                let (time, y) = (k as f64 + f, 1.0 + self.get(&s));
                if y >= 0.5 {
                    return match time > 0.0 {
                        true => before.0 + (time - before.0) * (0.5 - before.1) / (y - before.1),
                        false => 0.0,
                    };
                }
                before = (time, y);
            }
        }
        self.delay()
    }

    // the table position of `samples` (below 1): the entry and the remainder
    fn locate(samples: f64) -> (usize, f64) {
        let at = samples.clamp(0.0, 0.999_999) * PARTIAL_STEPS as f64;
        let index = at.floor();
        (index as usize, at - index)
    }

    /// The filter output now: the correction to add to the naive waveform.
    pub fn get(&self, state: &BlepState) -> f64 {
        state.re.iter().sum()
    }

    /// The stateless part of the answer to changes of slope: add it to
    /// `get`, with `slope` the waveform's slope now, per sample, counting every
    /// slope change that was `add`ed with order 2 (and the slope it started
    /// from as 0). It is the filter's delay: `K * slope`.
    pub fn slope_term(&self, slope: f64) -> f64 {
        self.ramp_offset * slope
    }

    /// The filter's DC group delay in samples (`-ramp_offset`): the time a
    /// slow signal is late by, and the lead a reader needs to cancel it.
    pub fn delay(&self) -> f64 {
        -self.ramp_offset
    }

    /// How long after a step the filter's output is half of it, in samples.
    /// It differs a little from `delay()`, which is the delay of what comes
    /// after the step.
    pub fn half_time(&self) -> f64 {
        self.half_time
    }

    /// Moves the state on by one sample.
    pub fn step(&self, state: &mut BlepState) {
        let p = &self.partial[PARTIAL_STEPS];
        for i in 0..POLES {
            let (re, im) = (state.re[i], state.im[i]);
            state.re[i] = re * p.re[i] - im * p.im[i];
            state.im[i] = re * p.im[i] + im * p.re[i];
        }
    }

    /// Adds a discontinuity of `order` (1 a step, 2 a change of slope per
    /// sample) and size `amount` that happened `samples_in_past` (below 1)
    /// before now.
    pub fn add(&self, state: &mut BlepState, amount: f64, order: usize, samples_in_past: f64) {
        if order > MAX_ORDER {
            return;
        }
        let (index, frac) = Self::locate(samples_in_past);
        // move the pulse along in time as `step` moves the state
        let (lo, hi) = (&self.ready[order][index], &self.ready[order][index + 1]);
        for i in 0..POLES {
            state.re[i] += amount * (lo.re[i] + (hi.re[i] - lo.re[i]) * frac);
            state.im[i] += amount * (lo.im[i] + (hi.im[i] - lo.im[i]) * frac);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // the first moment of the impulse response over its area is the DC group
    // delay; it is measured on the response itself, not on `ramp_offset`
    #[test]
    fn delay_is_the_dc_group_delay() {
        for sr in [44_100.0, 48_000.0, 96_000.0] {
            let t = BlepTable::new(sr);
            let mut s = QUIET;
            t.add(&mut s, 1.0, 0, 0.0);
            let (mut area, mut moment) = (0.0, 0.0);
            for n in 0..4_000 {
                let h = t.get(&s);
                area += h;
                moment += n as f64 * h;
                t.step(&mut s);
            }
            let measured = moment / area;
            assert!(
                (measured - t.delay()).abs() < 0.01,
                "{sr}: measured {measured}, delay {}",
                t.delay()
            );
            assert!(t.delay() > 0.0);
        }
        // a step is half done about where the delay says
        let t = BlepTable::new(48_000.0);
        assert!((t.half_time() - t.delay()).abs() < 0.5, "{}", t.half_time());
        // 2.63 frames at 48 kHz (55 us)
        assert!((BlepTable::new(48_000.0).delay() - 2.627).abs() < 0.01);
    }

    // the residue of a slope change dies away, leaving the naive ramp plus
    // `slope_term` (that this is `delay()` late is measured by
    // `delay_is_the_dc_group_delay`; this checks the response settles)
    #[test]
    fn a_ramp_response_decays_onto_the_delayed_ramp() {
        let t = BlepTable::new(48_000.0);
        let mut s = QUIET;
        t.add(&mut s, 1.0, 2, 0.0);
        for n in 0..2_000 {
            t.step(&mut s);
            if n > 500 {
                let y = (n + 1) as f64 + t.get(&s) + t.slope_term(1.0);
                assert!((y - ((n + 1) as f64 - t.delay())).abs() < 1e-6);
            }
        }
    }
}
